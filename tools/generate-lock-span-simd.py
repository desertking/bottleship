"""Encode a bounded, read-only SIMD byte-span helper; no v86 modification.
Opcode reference: https://github.com/WebAssembly/simd/blob/main/proposals/simd/BinarySIMD.md
Each function takes (a,b,n), two valid private-memory spans, returns first/last
unequal byte boundary. SIMD loops skip equal 16-byte blocks; scalar loops refine.
The caller bounds spans to 512 KiB, module memory is fixed at 1 MiB.
"""
from pathlib import Path

def u(n):
 out=[]
 while n>=128:out.append((n&127)|128);n>>=7
 return bytes(out+[n])
def sec(i,b):return bytes([i])+u(len(b))+b
def vec(xs):return u(len(xs))+b''.join(xs)
def name(s):b=s.encode();return u(len(b))+b
G=lambda i:bytes([0x20,i])
C=lambda i:bytes([0x41,i]) # only positive constants <= 16
END=b'\x0b'; ADD=b'\x6a'; SUB=b'\x6b'

def body(reverse):
 # params 0:a,1:b,2:n; local 3:i
 code=b'\x01\x01\x7f'+(G(2) if reverse else C(0))+b'\x21\x03'
 for width in [16,1]:
  code+=b'\x02\x40\x03\x40' # block exit / loop
  if reverse:code+=G(3)+C(width)+b'\x49' # i < width
  else:code+=G(2)+G(3)+SUB+C(width)+b'\x49' # n-i < width
  code+=b'\x0d\x01'
  at=G(3)+(C(width)+SUB if reverse else b'')
  load=b'\xfd\x00\x00\x00' if width==16 else b'\x2d\x00\x00'
  code+=G(0)+at+ADD+load+G(1)+at+ADD+load
  code+=b'\xfd\x51\xfd\x53' if width==16 else b'\x47' # xor.any_true / ne
  code+=b'\x0d\x01'+G(3)+C(width)+(SUB if reverse else ADD)+b'\x21\x03\x0c\x00'+END+END
 code+=G(3)+END
 return u(len(code))+code
wasm=b'\0asm\x01\0\0\0'
wasm+=sec(1,vec([b'\x60\x03\x7f\x7f\x7f\x01\x7f']))
wasm+=sec(3,vec([b'\x00',b'\x00']))
wasm+=sec(5,b'\x01\x01\x10\x10') # min/max 16 pages, no grow
wasm+=sec(7,vec([name('memory')+b'\x02\x00',name('prefix')+b'\x00\x00',name('suffix')+b'\x00\x01']))
wasm+=sec(10,u(2)+body(False)+body(True))

out=Path('src/worker/backends/webgpu/d3d9/lock-byte-span-simd.ts')
out.write_text('// Generated by tools/generate-lock-span-simd.py; exact byte prefix/suffix SIMD loops.\n// @transient(Immutable module bytecode generated from the stateless SIMD scan above)\nexport const LOCK_SPAN_SIMD = new Uint8Array(['+','.join(str(b) for b in wasm)+']);\n')
